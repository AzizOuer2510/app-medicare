-- PostgreSQL / M5 only. Run after M1's users table exists.
-- Existing tables and their data are left untouched: no ALTER, DROP, UPDATE or DELETE.
-- This is an installation script, not an upgrade of an older M5 schema.
BEGIN;

CREATE TABLE IF NOT EXISTS notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    title varchar(120) NOT NULL,
    message varchar(2000) NOT NULL,
    type varchar(20) NOT NULL CHECK (type IN ('GENERAL','APPOINTMENT','MEDICATION')),
    reference_id bigint,
    reminder_id bigint UNIQUE,
    created_at timestamptz NOT NULL,
    read_at timestamptz,
    archived boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS reminders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    author_id bigint REFERENCES users(id),
    instruction_at timestamptz,
    delivery_failed_at timestamptz,
    title varchar(120) NOT NULL,
    message varchar(2000) NOT NULL,
    type varchar(20) NOT NULL CHECK (type IN ('GENERAL','APPOINTMENT','MEDICATION')),
    reference_id bigint,
    scheduled_for timestamptz NOT NULL,
    status varchar(20) NOT NULL CHECK (status IN ('PENDING','SENT','CANCELLED')),
    created_at timestamptz NOT NULL,
    sent_at timestamptz
);

CREATE TABLE IF NOT EXISTS patient_doctor (
    patient_id bigint NOT NULL,
    doctor_id bigint NOT NULL REFERENCES users(id),
    PRIMARY KEY (patient_id, doctor_id)
);

CREATE TABLE IF NOT EXISTS reminder_change (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reminder_id bigint,
    actor_id bigint,
    actor_name varchar(255),
    action varchar(255),
    changed_at timestamptz
);

CREATE TABLE IF NOT EXISTS medical_documents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    shared_doctor_id bigint REFERENCES users(id),
    title varchar(120) NOT NULL,
    category varchar(20) NOT NULL CHECK (category IN ('PRESCRIPTION','ANALYSIS','OTHER')),
    description varchar(2000),
    original_filename varchar(200) NOT NULL,
    storage_key varchar(50) NOT NULL UNIQUE,
    content_type varchar(50) NOT NULL,
    size bigint NOT NULL,
    uploaded_at timestamptz NOT NULL,
    favorite boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS document_shares (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id bigint NOT NULL REFERENCES medical_documents(id) ON DELETE CASCADE,
    token_hash varchar(64) NOT NULL UNIQUE,
    pin_hash varchar(60) NOT NULL,
    label varchar(80) NOT NULL,
    created_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    failed_attempts integer NOT NULL DEFAULT 0,
    access_count bigint NOT NULL DEFAULT 0,
    last_access_at timestamptz
);

CREATE TABLE IF NOT EXISTS document_share_accesses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    share_id bigint NOT NULL REFERENCES document_shares(id) ON DELETE CASCADE,
    accessed_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS document_analyses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id bigint NOT NULL UNIQUE REFERENCES medical_documents(id) ON DELETE CASCADE,
    status varchar(255) NOT NULL,
    started_at timestamptz,
    requested_by_id bigint,
    draft_json text,
    error varchar(255)
);

COMMIT;
